// 겹친 오버레이의 뒤로가기 조정.
//
// 문제: 편집실(StudioShell)과 그 안에 렌더되는 공개 포스터(PublicPoster)가 **각각** popstate를
// 듣는다. 편집실은 '시청자 미리보기'를, 포스터는 '이 달 기록' 시트를 히스토리 한 칸으로 관리한다.
// popstate는 두 리스너에 모두 가므로, 뒤로가기 한 번에 시트도 닫히고 미리보기까지 닫혀 편집실로
// 튕겼다(신고된 증상).
//
// 처음엔 "안쪽이 처리한 이벤트에 표식을 남기고 바깥은 건너뛴다"로 했는데 **틀렸다**: 실측해 보니
// 바깥(편집실) 리스너가 먼저 불리고, 그 안에서 미리보기를 닫아 포스터가 언마운트되는 바람에
// 안쪽 리스너는 실행조차 못 했다(제거된 리스너는 그 dispatch에서 호출되지 않는다).
//
// 그래서 순서에 기대지 않는다. 안쪽이 히스토리에 자기 칸을 쌓아둔 동안에는 카운터를 올려두고,
// 바깥은 "안쪽 칸이 남아 있으면 이번 pop은 안쪽 것"이라 보고 손을 뗀다. 안쪽이 실제로 닫히면서
// 카운터를 내리므로, 다음 뒤로가기는 바깥 차례가 된다.
let innerDepth = 0;

/** 안쪽 오버레이가 히스토리 한 칸을 쌓았다(열림). */
export function pushInnerOverlay(): void {
  innerDepth += 1;
}

/** 안쪽 오버레이가 닫혀 그 칸이 사라졌다. */
export function popInnerOverlay(): void {
  innerDepth = Math.max(0, innerDepth - 1);
}

/** 바깥(편집실)용 — 안쪽 오버레이가 열려 있으면 이번 뒤로가기는 그쪽 몫이다. */
export function hasInnerOverlay(): boolean {
  return innerDepth > 0;
}
